"""Export genuine NewTX LaTeX mathematics as reusable SVG paths.

The SVG geometry is generated by TeX, not approximated by Unicode text.
Each result includes its original LaTeX expression and baseline coordinates.
Requires a TeX engine with amsmath, newtxtext/newtxmath, bm, xcolor and geometry.
"""
from pathlib import Path
import argparse, json, subprocess, re, shutil
import pymupdf as fitz

def render_math(items, output, tectonic='tectonic', class_file=None, only_cached=False):
    output = Path(output); output.mkdir(parents=True, exist_ok=True)
    preamble = r'''\documentclass{article}
\makeatletter
\renewcommand\normalsize{\@setfontsize\normalsize{10bp}{12bp}}
\makeatother
\normalsize
\usepackage{amsmath,amssymb,newtxtext,newtxmath,bm,xcolor}
\usepackage[paperwidth=250bp,paperheight=100bp,margin=20bp]{geometry}
\pagestyle{empty}\setlength{\parindent}{0pt}
\newcommand{\vect}[1]{\bm{#1}}
\begin{document}
'''
    pages = []
    if class_file:
        shutil.copy2(class_file, output/'sn-jnl.cls')
        preamble=preamble.replace(r'\documentclass{article}',r'\documentclass[pdflatex,sn-mathphys-num]{sn-jnl}')
        preamble=preamble.replace(r'\usepackage[paperwidth=250bp,paperheight=100bp,margin=20bp]{geometry}',r'\geometry{paperwidth=250bp,paperheight=100bp,margin=20bp}')
    for item in items:
        size = item.get('size',25)
        pages.append(r'\fontsize{%s}{%s}\selectfont\noindent\hbox{\color{white}X\color{black}$%s$}' % (size, size*1.2, item['latex']))
    tex = preamble + '\n\\newpage\n'.join(pages) + '\n\\end{document}\n'
    (output/'math.tex').write_text(tex,encoding='utf-8')
    command=[str(tectonic),'-X','compile','math.tex','--keep-logs']
    if only_cached:command.append('--only-cached')
    run = subprocess.run(command,cwd=output,capture_output=True,text=True)
    (output/'compile.txt').write_text(run.stdout+run.stderr,encoding='utf-8')
    if run.returncode: raise RuntimeError(run.stdout+run.stderr)
    doc=fitz.open(output/'math.pdf'); assert len(doc)==len(items)
    results={}
    for page,item in zip(doc,items):
        spans=[s for b in page.get_text('dict')['blocks'] for l in b.get('lines',[]) for s in l['spans']]
        white=[s for s in spans if s['color']==0xffffff]
        assert white, spans
        baseline=white[0]['origin'][1]
        black=[s for s in spans if s['color']!=0xffffff]
        rect=fitz.Rect(black[0]['bbox'])
        for span in black[1:]: rect |= fitz.Rect(span['bbox'])
        rect += (-0.12,-0.12,0.12,0.12)
        page.set_cropbox(rect)
        svg=page.get_svg_image(text_as_path=True)
        (output/(item['id']+'.svg')).write_text(svg,encoding='utf-8')
        results[item['id']]={'latex':item['latex'],'size':item.get('size',25),
            'width':rect.width,'height':rect.height,'baseline':baseline-rect.y0}
    (output/'metrics.json').write_text(json.dumps(results,indent=2),encoding='utf-8')
    return results

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--manifest',required=True,type=Path)
    p.add_argument('--output',required=True,type=Path)
    p.add_argument('--tectonic',default='tectonic')
    p.add_argument('--class-file',type=Path,help='Optional installed Springer class for matching its local TeX setup.')
    p.add_argument('--only-cached',action='store_true',help='Disable dependency downloads when a full TeX cache is already available.')
    args=p.parse_args()
    render_math(json.loads(args.manifest.read_text(encoding='utf-8')),args.output,args.tectonic,args.class_file,args.only_cached)
